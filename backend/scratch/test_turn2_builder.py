import asyncio
from app.core.db import AsyncSessionLocal
from app.services.builder_service import BuilderService
from app.schemas.agent import ChatMessage

async def main():
    async with AsyncSessionLocal() as db:
        prompt_1 = "Halo, saya ingin membuat asisten toko online untuk mengecek resi pengiriman dan status paket pelanggan."
        resp_1 = await BuilderService.build_agent_spec(db=db, prompt=prompt_1)
        
        prompt_2 = (
            "Hanya boleh membaca status paket saja, jangan ubah apa-apa. "
            "Datanya ambil dari API toko saya di https://api.tokoonline.com/v1/tracking/{tracking_no} dengan method GET."
        )
        history = [
            ChatMessage(role="user", content=prompt_1),
            ChatMessage(role="assistant", content=resp_1.message),
        ]
        
        print("\n--- TURN 2: USER JAWAB C4 DAN C3 DENGAN API ENDPOINT ---")
        resp_2 = await BuilderService.build_agent_spec(
            db=db,
            prompt=prompt_2,
            current_spec=resp_1.spec,
            history=history
        )
        print("Message:")
        print(resp_2.message)
        print("\nNew Tools Generated by Tool Factory:")
        print(resp_2.new_tools)
        print("\nSpec:")
        print(resp_2.spec.name if resp_2.spec else None)
        print(resp_2.spec.tools if resp_2.spec else None)

if __name__ == "__main__":
    asyncio.run(main())
